// Client-side translations for assessment questions & options.
//
// Questions/options are stored in English in the DB, so this catalog maps
// each question (by `question_order`) and each option (by
// `${question_order}_${option_value}`) to the active locale. Falls back to
// the DB English text when a locale has no entry.

export interface AssessmentTranslation {
  q: Record<number, string>;
  o: Record<string, string>;
}

export function translateQuestion(locale: string, order: number, fallback: string): string {
  return assessmentTranslations[locale]?.q?.[order] ?? fallback;
}

export function translateOption(locale: string, order: number, optionValue: string, fallback: string): string {
  return assessmentTranslations[locale]?.o?.[`${order}_${optionValue}`] ?? fallback;
}

export function translateAssessment<T extends {
  question_text: string;
  question_order: number;
  options: { option_text: string; option_value: string }[];
}>(
  locale: string,
  questions: T[]
) {
  return questions.map((q) => ({
    ...q,
    question_text: translateQuestion(locale, q.question_order, q.question_text),
    options: q.options.map((o) => ({
      ...o,
      option_text: translateOption(locale, q.question_order, o.option_value, o.option_text),
    })),
  }));
}

